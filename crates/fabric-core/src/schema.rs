    #[test]
    fn agent_run_result_schema_enforces_failure_and_artifact_invariants() {
        let schema = generate_schema(SchemaName::AgentRunResult).expect("schema generation");
        let validator = jsonschema::validator_for(&schema).expect("valid result schema");

        assert!(!validator.is_valid(&serde_json::json!({
            "status": "failed",
            "output": null
        })));
        assert!(!validator.is_valid(&serde_json::json!({
            "status": "succeeded",
            "output": null,
            "error": {"code": "target_error", "message": "target failed"}
        })));
        for path in [
            " \t",
            "nested/../output",
            r"nested\..\output",
            r"C:\tmp\output",
            r"C:output",
            r"\\server\output",
        ] {
            assert!(!validator.is_valid(&serde_json::json!({
                "status": "succeeded",
                "output": null,
                "artifacts": [{
                    "name": "output",
                    "kind": "file",
                    "path": path
                }]
            })));
        }
        assert!(!validator.is_valid(&serde_json::json!({
            "status": "succeeded",
            "output": null,
            "artifacts": [{
                "name": "output",
                "kind": "file",
                "path": "/tmp/output"
            }]
        })));
        assert!(validator.is_valid(&serde_json::json!({
            "status": "failed",
            "output": null,
            "error": {"code": "target_error", "message": "target failed"}
        })));
    }
